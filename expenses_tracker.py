# Описание: Программа для суммирования ежедневных 
# трат с проверкой установленного лимита бюджета.
# ==========================================

# Инициализируем переменную для накопления общей суммы. 
# Начинаем с нуля.
total = 0 

print("--- Учет расходов ---")
print("Вводите суммы трат по одной. Для завершения введите 0.\n")

# Запускаем бесконечный цикл для непрерывного ввода данных
while True:
    # Используем float, чтобы пользователь мог вводить суммы с копейками (например, 150.50)
    expense = float(input("Сумма траты (руб): "))
    
    # 0 служит сигнальной меткой (sentinel value) для остановки ввода
    if expense == 0:
        break
        
    # Если введено не 0, прибавляем текущую трату к общей сумме
    total += expense

# Выводим итоговый результат, оставляя 2 знака после запятой для денежного формата
print(f"\nОбщая сумма ваших трат: {total:.2f} руб.")

# Проверяем бизнес-логику: не превышен ли установленный лимит
if total > 3000:
    print("Ого, ты слишком много тратишь! Пора экономить.")
else:
    print("Отличный контроль бюджета! Так держать.")
